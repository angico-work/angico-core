CREATE TABLE IF NOT EXISTS resultado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id VARCHAR(255),
    acao_id BIGINT,
    titulo VARCHAR(200),
