CREATE TABLE IF NOT EXISTS recurso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id VARCHAR(255) NOT NULL,
    nome VARCHAR(200) NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    unidade VARCHAR(40) NOT NULL,
    descricao VARCHAR(2000),
    status VARCHAR(20) NOT NULL,
    actor_id VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_recurso_workspace_nome
    ON recurso (workspace_id, nome);

CREATE TABLE IF NOT EXISTS uso_recurso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id VARCHAR(255) NOT NULL,
    recurso_id BIGINT NOT NULL,
    acao_id BIGINT NOT NULL,
    quantidade NUMERIC(16, 4) NOT NULL,
    unidade VARCHAR(40) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id VARCHAR(255) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_uso_recurso_workspace_resource
    ON uso_recurso (workspace_id, recurso_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_uso_recurso_workspace_action
    ON uso_recurso (workspace_id, acao_id);
